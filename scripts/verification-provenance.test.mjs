import { describe, expect, it } from "vitest";
import { verifyEvidence } from "./verification-provenance.mjs";

function completeEvidence() {
  return ["ubuntu-latest", "windows-latest"].flatMap((os) =>
    ["npm", "pnpm"].flatMap((manager) =>
      ["24.11.0", "24"].map((nodeSelector) => ({
        os,
        manager,
        nodeSelector,
        revision: "same-immutable-source",
        locks: { "package-lock.json": "a".repeat(64), "pnpm-lock.yaml": "b".repeat(64) },
        generated: {
          "src/generated/catalog.ts": "c".repeat(64),
          "src/generated/agents.ts": "9".repeat(64),
          "public/catalog/v1/index.json": "d".repeat(64),
          "public/catalog/v1/tools.json": "e".repeat(64),
        },
        markdown: "f".repeat(64),
      })),
    ),
  );
}

describe("complete acceptance evidence", () => {
  it("accepts equal generated bytes across all fresh platform graphs", () => {
    expect(() => verifyEvidence(completeEvidence())).not.toThrow();
  });
  it("rejects missing, duplicate and mixed-revision evidence", () => {
    const records = completeEvidence();
    expect(() => verifyEvidence(records.slice(1))).toThrow("Missing acceptance evidence");
    expect(() => verifyEvidence([...records, records[0]])).toThrow("Duplicate");
    records[0] = { ...records[0], revision: "other-source" };
    expect(() => verifyEvidence(records)).toThrow("mixes source revisions");
  });
  it("rejects graph and generated-byte drift", () => {
    const records = completeEvidence();
    records[1] = {
      ...records[1],
      generated: { ...records[1].generated, "src/generated/catalog.ts": "0".repeat(64) },
    };
    expect(() => verifyEvidence(records)).toThrow("parity failed");
    records[1] = {
      ...records[0],
      nodeSelector: "24",
      locks: { "package-lock.json": "0".repeat(64), "pnpm-lock.yaml": "b".repeat(64) },
    };
    expect(() => verifyEvidence(records)).toThrow("mixes dependency locks");
  });
  it("rejects agent generated output drift", () => {
    const records = completeEvidence();
    records[1].generated["src/generated/agents.ts"] = "0".repeat(64);
    expect(() => verifyEvidence(records)).toThrow("parity failed");
  });
  it("rejects Markdown parser output drift", () => {
    const records = completeEvidence();
    records[1] = { ...records[1], markdown: "different-rendering" };
    expect(() => verifyEvidence(records)).toThrow("Markdown rendering parity failed");
  });
  it("rejects incomplete hash payloads", () => {
    const records = completeEvidence();
    records[0] = { ...records[0], generated: {} };
    expect(() => verifyEvidence(records)).toThrow("Missing generated hash");
  });
});
